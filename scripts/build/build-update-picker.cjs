#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const { builtinModules } = require('node:module');
const { buildSync } = require('esbuild');
function buildUpdatePicker(root = path.resolve(__dirname, '../..')) {
  const result = buildSync({ absWorkingDir: root, entryPoints: ['src/zak/kit-update-prompt.mjs'],
    nodePaths: [path.resolve(__dirname, '../../node_modules')],
    bundle: true, platform: 'node', target: 'node26', format: 'cjs', minify: true,
    write: false, metafile: true });
  for (const output of Object.values(result.metafile.outputs))
    for (const dependency of output.imports)
      if (!builtinModules.includes(dependency.path.replace(/^node:/, '')))
        throw new Error(`external picker dependency: ${dependency.path}`);
  const output = path.join(root, 'dist/installer/update-picker.cjs');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  const temporary = `${output}.${process.pid}.tmp`;
  try {
    fs.writeFileSync(temporary, '// Generated by build-update-picker.cjs; do not edit.\n' + result.outputFiles[0].text);
    fs.renameSync(temporary, output);
  } finally { fs.rmSync(temporary, { force: true }); }
  return output;
}
if (require.main === module) console.log(buildUpdatePicker());
module.exports = { buildUpdatePicker };
